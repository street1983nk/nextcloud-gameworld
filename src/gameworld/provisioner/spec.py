"""The hardened container spec of a world.

The values are hard-coded (WELT-05): parents set no limits, and no
value from user input gets here. The arguments are the instance ID generated by the app,
the world ID, the assigned host port and a preset from the
fixed registry (memory limit and label come only from there).
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import BinaryIO

from docker.types import Mount

from gameworld.provisioner.presets import Preset

LUANTI_VERSION = "5.17.0"
LUANTI_IMAGE = "ghcr.io/luanti-org/luanti@sha256:db682caec367977ac2661c81e3cdbd1f1dbbae596f6fa7d791c0031107d59947"
DATA_DIR = "/var/lib/minetest"
INTERNAL_PORT = "30000/udp"


def resource_name(instance_id: str, world_id: str) -> str:
    """Name of container and volume, always with the instance prefix."""
    return f"gameworld-{instance_id}-{world_id}"


@dataclass(frozen=True)
class WorldPayload:
    """Preset and tar file object for ``put_archive``.

    Stands here instead of in archive.py, because client.py must not import archive.py
    (archive.py imports ProvisionerError from client.py).
    """

    preset: Preset
    archive: BinaryIO


def world_spec(instance_id: str, world_id: str, host_port: int, preset: Preset) -> dict[str, object]:
    """Keyword arguments for ``containers.create``."""
    name = resource_name(instance_id, world_id)
    return {
        "image": LUANTI_IMAGE,
        "name": name,
        "command": ["--config", f"{DATA_DIR}/minetest.conf", "--world", f"{DATA_DIR}/.minetest/worlds/world"],
        "user": "30000:30000",
        "labels": {
            "gameworld.managed": "true",
            "gameworld.instance": instance_id,
            "gameworld.world_id": world_id,
            # Schema 2: preset set and world mod gameworld_status present.
            # 02-04 evaluates readiness (status file) only from schema 2 on.
            "gameworld.schema": "2",
            "gameworld.preset": preset.id,
            "gameworld.engine": "luanti",
            "gameworld.engine_version": LUANTI_VERSION,
            "gameworld.port": str(host_port),
        },
        "mounts": [Mount(target=DATA_DIR, source=name, type="volume")],
        # tmpfs prevents anonymous volumes from the VOLUME directives of the image.
        "tmpfs": {"/etc/minetest": "size=1m", "/tmp": "size=16m"},  # noqa: S108
        # Internally always 30000, externally the assigned port; LAN players need 0.0.0.0.
        "ports": {INTERNAL_PORT: ("0.0.0.0", host_port)},  # noqa: S104
        # The same limit for memory and swap: no swapping out on the home server.
        "mem_limit": preset.mem_limit,
        "memswap_limit": preset.mem_limit,
        "pids_limit": 128,
        "nano_cpus": 1_000_000_000,
        "cap_drop": ["ALL"],
        "security_opt": ["no-new-privileges:true"],
        "read_only": True,
        # No automatic restart: prevents OOM crash loops on the home server.
        "restart_policy": {"Name": "no"},
        "log_config": {"Type": "json-file", "Config": {"max-size": "5m", "max-file": "2"}},
    }
